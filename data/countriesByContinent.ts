/** 展示用标签：中文 (English) */
export const countryLabel = (c: CountryItem) => `${c.zh} (${c.en})`;

/** 英文名，供搜索 API 使用 */
export const countrySearchValue = (c: CountryItem) => c.en;

export const findCountryByEn = (en: string): CountryItem | undefined => {
  const key = en.trim().toLowerCase();
  for (const continent of CONTINENTS) {
    const hit = continent.countries.find(
      (c) => c.en.toLowerCase() === key || c.zh === en.trim() || c.code.toLowerCase() === key
    );
    if (hit) return hit;
  }
  return undefined;
};
